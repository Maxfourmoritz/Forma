import type { Equipment, Exercise, Goal, Muscle, PathId, Pattern } from './types';

type Def = Omit<Exercise, 'goals' | 'quiet' | 'space' | 'joints' | 'rest' | 'equipment' | 'muscles' | 'secPerRep'> & {
  goals?: Goal[];
  quiet?: boolean;
  space?: Exercise['space'];
  joints?: Exercise['joints'];
  rest?: number;
  equipment?: Equipment[];
  p: Muscle[];
  s?: Muscle[];
  secPerRep?: number;
};

const PATTERN_GOALS: Record<Pattern, Goal[]> = {
  push_h: ['kraft', 'muskelaufbau'],
  push_v: ['kraft', 'muskelaufbau', 'haltung'],
  pull_h: ['kraft', 'muskelaufbau', 'haltung'],
  pull_v: ['kraft', 'muskelaufbau', 'haltung'],
  squat: ['kraft', 'muskelaufbau'],
  hinge: ['kraft', 'muskelaufbau', 'haltung'],
  anti_ext: ['rumpf', 'haltung'],
  lateral: ['rumpf'],
  extension: ['rumpf', 'haltung'],
  balance: ['balance'],
  calf: ['kraft', 'balance'],
  mobility: ['beweglichkeit', 'erholung'],
  warmup: ['aufwaermen'],
};

function ex(d: Def): Exercise {
  const { p, s, ...rest } = d;
  return {
    goals: PATTERN_GOALS[d.pattern],
    quiet: true,
    space: 'klein',
    joints: {},
    rest: d.mode === 'reps' ? 75 : 45,
    equipment: [],
    secPerRep: 3.5,
    ...rest,
    muscles: { primary: p, secondary: s ?? [] },
  };
}

